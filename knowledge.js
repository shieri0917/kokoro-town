/** AI応答末尾に出力させるタグの正規表現（chat.jsでのパースに使う） */
const RESPONSE_TAGS = {
  SMALL_STEP: /\[SMALL_STEP\]\s*(.+)/,
  PACE_DECLARATION: /\[PACE_DECLARATION\]\s*(.+)/,
  STRENGTH_FOUND: /\[STRENGTH_FOUND\]\s*(.+)/,
};

/** 応答テキストからタグ行を取り除き、表示用テキストとタグの内容を分離する */
function extractResponseTags(rawText) {
  let displayText = rawText;
  const found = {};
  for (const [key, regex] of Object.entries(RESPONSE_TAGS)) {
    const match = displayText.match(regex);
    if (match) {
      found[key] = match[1].trim();
      displayText = displayText.replace(match[0], "").trim();
    }
  }
  return { displayText, tags: found };
}

